// Inlines proposals/ratings-v1.json into the tactical spike engine so it can run in the browser/vm sandbox.
const fs = require('fs'), path = require('path');
const ratings = fs.readFileSync(path.join(__dirname, '..', 'ratings-v1.json'), 'utf8');
const src = fs.readFileSync(path.join(__dirname, 'engine-tactical.src.js'), 'utf8');
fs.writeFileSync(path.join(__dirname, 'engine-tactical.js'), '// GENERATED by build.cjs — edit engine-tactical.src.js\nconst RATINGS_V1 = ' + ratings + ';\n' + src);
console.log('built engine-tactical.js');
