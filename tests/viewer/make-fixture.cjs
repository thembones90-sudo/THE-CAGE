// Regenerates the viewer's built-in fixture record from the CURRENT engine.
// This is a developer tool run from Node, never from the viewer. The viewer only
// reads the frozen JSON it writes; it never simulates.
// Usage: node tests/viewer/make-fixture.cjs [--probe]
'use strict';
const fs = require('node:fs'), path = require('node:path');
const { loadEngine, root } = require('./harness.cjs');

const W = loadEngine();
const E = W.CageEngine;
const input = { teams: [['paolo-maldini', 'michael-ballack', 'ronaldo-nazario'], ['ronaldinho', 'rivaldo', 'alessandro-del-piero']], tactics: ['balanced', 'counter'], seed: 42, mode: 'ko' };
const result = E.simulate(input);
const record = JSON.parse(JSON.stringify(W.CageRecords.make(input, result, 1)));
record.createdAt = '2026-10-30T00:00:00.000Z'; // fixed so the fixture file is byte-stable

if (process.argv.includes('--probe')) {
  const types = {};
  result.events.forEach(e => { types[e.type] = (types[e.type] || 0) + 1; });
  console.log(E.VERSION, E.PARAMS_VERSION, result.events.length, 'events', result.duration, 's', result.score, types);
  for (const t of Object.keys(types)) console.log(JSON.stringify(result.events.find(e => e.type === t)));
  process.exit(0);
}

const outJson = path.join(__dirname, 'fixtures', 't3-schema1-seed42.json');
fs.mkdirSync(path.dirname(outJson), { recursive: true });
fs.writeFileSync(outJson, JSON.stringify(record));
const outJs = path.join(root, 'src', 'viewer', 'fixture-default.js');
fs.writeFileSync(outJs, '// Built-in fixture: a recorded T3 match (engine ' + record.engineVersion + ', seed 42).\n' +
  '// Generated by tests/viewer/make-fixture.cjs. Recorded data only; the viewer never simulates.\n' +
  'window.CAGE_VIEWER_FIXTURE=' + JSON.stringify(record) + ';\n');
console.log('wrote', outJson, 'and', outJs, record.result.events.length, 'events, hash', record.result.eventHash);

// v0.4 record (no off-ball positions) for the ball-only mode test, from the archived engine.
const vm = require('node:vm'), old = { window: {} }; vm.createContext(old);
for (const f of ['players', 'roster-expansion', 'engine/legacy-v04', 'replay/records']) vm.runInContext(fs.readFileSync(path.join(root, 'src', f + '.js'), 'utf8'), old, { filename: f });
const legacy = JSON.parse(JSON.stringify(old.window.CageRecords.make(input, old.window.CageEngine.simulate(input), 1)));
legacy.createdAt = '2026-10-30T00:00:00.000Z';
fs.writeFileSync(path.join(__dirname, 'fixtures', 'v04-seed42.json'), JSON.stringify(legacy));
console.log('wrote v04-seed42.json', legacy.engineVersion, legacy.result.events.length, 'events');
